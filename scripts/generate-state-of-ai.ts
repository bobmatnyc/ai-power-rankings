/**
 * Generate the monthly report (Direct Service Call)
 * Bypasses API authentication for local testing
 * #182: runs the one monthly generator (`WhatsNewSummaryService`), which appends
 * a version to `monthly_report_versions`; it no longer writes state_of_ai_summaries.
 *
 * Usage: npx tsx scripts/generate-state-of-ai.ts [month] [year]
 */

import dotenv from "dotenv";
import { WhatsNewSummaryService } from "../lib/services/whats-new-summary.service";
import { monthYearToPeriod } from "../lib/services/monthly-report.repository";

// Load environment variables
dotenv.config({ path: ".env.local" });

async function generateMonthlyReport() {
  try {
    console.log("🚀 Starting monthly report generation...\n");

    // Get month and year from command line args, or use current date
    const now = new Date();
    const month = process.argv[2] ? parseInt(process.argv[2], 10) : now.getMonth() + 1;
    const year = process.argv[3] ? parseInt(process.argv[3], 10) : now.getFullYear();

    // Validate inputs
    if (month < 1 || month > 12) {
      throw new Error("Month must be between 1 and 12");
    }

    if (year < 2020 || year > 2030) {
      throw new Error("Year must be between 2020 and 2030");
    }

    console.log(`📅 Target: ${getMonthName(month)} ${year}`);
    console.log(`👤 Generated by: cli-script\n`);

    // Create service and generate
    const service = new WhatsNewSummaryService();
    const startTime = Date.now();

    console.log("⚡ Generating the monthly report...");
    console.log("   (This may take 30-60 seconds)\n");

    const result = await service.generateMonthlySummary(
      monthYearToPeriod(month, year),
      true, // Force regenerate: appends a new version
      "cli-script"
    );

    const duration = Date.now() - startTime;

    console.log(`✅ Generation complete in ${duration}ms\n`);

    // Display results
    console.log("📊 Summary Details:");
    console.log(`   ID: ${result.summary.id}`);
    console.log(`   Period: ${result.summary.period} (version ${result.summary.version})`);
    console.log(`   Generated: ${result.summary.generatedAt.toISOString()}`);
    console.log(`   Content Length: ${result.summary.content.length} chars`);
    console.log(`   Is New: ${result.isNew}`);
    console.log(`   Generation Time: ${result.generationTimeMs}ms\n`);

    // Display first 500 characters of content
    console.log("📄 Content Preview:");
    console.log("─".repeat(80));
    console.log(result.summary.content.substring(0, 500));
    if (result.summary.content.length > 500) {
      console.log("\n... (truncated, see database for full content)");
    }
    console.log("─".repeat(80));

    console.log("\n✅ Monthly report version saved to database!");
    console.log("\n📋 Next steps:");
    console.log("   1. Verify in admin UI:");
    console.log("      → http://localhost:3007/en/admin/state-of-ai");
    console.log("   2. View on What's New page:");
    console.log("      → http://localhost:3007/en/whats-new");
    console.log("   3. Test public API:");
    console.log("      → curl http://localhost:3007/api/state-of-ai/current\n");
  } catch (error) {
    console.error("\n❌ Generation failed:");
    console.error(error instanceof Error ? error.message : "Unknown error");
    if (error instanceof Error && error.stack) {
      console.error("\nStack trace:");
      console.error(error.stack);
    }
    process.exit(1);
  }
}

function getMonthName(month: number): string {
  const months = [
    "January",
    "February",
    "March",
    "April",
    "May",
    "June",
    "July",
    "August",
    "September",
    "October",
    "November",
    "December",
  ];
  return months[month - 1] || "Unknown";
}

// Run generation
generateMonthlyReport();
