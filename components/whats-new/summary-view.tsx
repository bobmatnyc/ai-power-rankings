import Link from 'next/link';
import { Calendar } from 'lucide-react';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import { Badge } from '@/components/ui/badge';
import { Separator } from '@/components/ui/separator';
import { formatPeriod } from '@/lib/whats-new-period';

/** The stored-summary fields the view renders (a `monthly_summaries` row). */
export interface SummaryViewData {
  period: string;
  content: string;
  generatedAt: Date | string;
  metadata: unknown;
}

interface SummaryStats {
  model?: string;
  article_count?: number;
  ranking_change_count?: number;
  new_tool_count?: number;
  site_change_count?: number;
}

/**
 * One monthly What's New report: month heading, generation line, markdown
 * body and statistics.
 *
 * Why: #54: the `/whats-new` index and each `/whats-new/<period>` permalink
 * render the same report, so the markup moved here from the index page.
 * What: `headingLevel` picks `h1` (permalink) or `h2` (index, under the
 * layout's h1). The markdown renders through react-markdown without
 * `rehype-raw`, so raw HTML in a summary is shown as text, never executed.
 * Dates format in UTC. `permalinkHref`, when given, adds a link to the
 * report's own page.
 * Test: `tests/unit/whats-new-permalink.test.ts`.
 */
export function SummaryView({
  summary,
  headingLevel,
  permalinkHref,
}: {
  summary: SummaryViewData;
  headingLevel: 'h1' | 'h2';
  permalinkHref?: string;
}) {
  const Heading = headingLevel;
  const stats = (summary.metadata ?? {}) as SummaryStats;
  const formattedGenerated = new Date(summary.generatedAt).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    timeZone: 'UTC', // #54: same day on every server, whatever its zone
  });

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex items-center justify-between flex-wrap gap-4">
        <div>
          <Heading className="text-2xl font-bold mb-2">{formatPeriod(summary.period)}</Heading>
          <div className="flex items-center gap-2 text-sm text-muted-foreground">
            <Calendar className="h-4 w-4" />
            <span>Generated {formattedGenerated}</span>
            {stats.article_count !== undefined && (
              <>
                <span>•</span>
                <span>{stats.article_count} articles analyzed</span>
              </>
            )}
          </div>
          {permalinkHref && (
            <Link href={permalinkHref} className="text-sm text-ds-accent-fixed hover:underline">
              Permanent link to this report
            </Link>
          )}
        </div>
        {stats.model && (
          <Badge variant="outline" className="text-xs">
            Generated by {stats.model}
          </Badge>
        )}
      </div>

      <Separator />

      {/* Summary Content */}
      <div className="prose prose-sm max-w-none dark:prose-invert prose-headings:font-semibold prose-a:text-primary hover:prose-a:underline prose-p:leading-relaxed prose-li:my-1">
        <ReactMarkdown remarkPlugins={[remarkGfm]}>{summary.content}</ReactMarkdown>
      </div>

      {/* Statistics */}
      <Separator className="my-8" />
      <div className="grid grid-cols-2 md:grid-cols-4 gap-6">
        <Stat value={stats.article_count} label="Articles" />
        <Stat value={stats.new_tool_count} label="New Tools" />
        <Stat value={stats.ranking_change_count} label="Ranking Updates" />
        <Stat value={stats.site_change_count} label="Site Updates" />
      </div>
    </div>
  );
}

function Stat({ value, label }: { value: number | undefined; label: string }) {
  if (value === undefined) return null;
  return (
    <div className="text-center p-4 rounded-lg bg-muted/50">
      <div className="text-3xl font-bold text-primary mb-1">{value}</div>
      <div className="text-sm text-muted-foreground">{label}</div>
    </div>
  );
}

/**
 * "Past reports": a link to every stored period's permalink (#54).
 *
 * What: Newest first, as `listPeriods()` returns them; the current period is
 * shown without a link. Renders nothing for a single report.
 */
export function PastReports({
  lang,
  periods,
  current,
}: {
  lang: string;
  periods: readonly string[];
  current: string;
}) {
  if (periods.length < 2) return null;
  return (
    <nav aria-label="Past reports" className="border-t border-ds-border-paper pt-6">
      <h2 className="text-lg font-semibold mb-3">Past reports</h2>
      <ul className="space-y-1 text-sm">
        {periods.map((period) => (
          <li key={period}>
            {period === current ? (
              <span className="text-ds-text-paper-muted">{formatPeriod(period)}</span>
            ) : (
              <Link href={`/${lang}/whats-new/${period}`} className="text-ds-accent-fixed hover:underline">
                {formatPeriod(period)}
              </Link>
            )}
          </li>
        ))}
      </ul>
    </nav>
  );
}
